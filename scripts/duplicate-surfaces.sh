#!/bin/sh
# ticket 291 item 4 (needs 210): the removal-round list. Reads scripts/duplicate-surfaces.tsv (state or action, surface, file,
# label), checks that every file exists and still holds its label (a stale row fails, and every stale row is named), and writes
# the Markdown page the owner cuts from to OUT (default .scratch/removal-round.md). A generated list, not a gate.
# DUP_TABLE / DUP_OUT / DUP_ROOT (tests): another table, output file and the folder the table's files are relative to.
set -u
cd "$(dirname "$0")/.." || exit 2
table=${DUP_TABLE:-scripts/duplicate-surfaces.tsv}; out=${DUP_OUT:-.scratch/removal-round.md}; root=${DUP_ROOT:-.}
[ -f "$table" ] || { echo "duplicate-surfaces: $table missing" >&2; exit 2; }
mkdir -p "$(dirname "$out")" || exit 2
tab=$(printf '\t'); stale=0
rows=$(grep -v '^#' "$table" | grep -v '^[[:space:]]*$')
{
  echo "# Removal round: places that show the same state or action twice"
  echo
  echo "Generated by scripts/duplicate-surfaces.sh from scripts/duplicate-surfaces.tsv. Tick the surfaces to cut; the rest stay."
  prev=""
  while IFS="$tab" read -r what surface file label; do
    if [ -z "$what" ] || [ -z "$surface" ] || [ -z "$file" ] || [ -z "$label" ]; then echo "duplicate-surfaces: bad row (4 tab-separated fields): $what|$surface" >&2; stale=1; continue; fi
    if [ "$what" != "$prev" ]; then
      n=$(printf '%s\n' "$rows" | awk -F'\t' -v w="$what" '$1 == w' | wc -l | tr -d ' ')
      printf '\n## %s (%s places)\n\n' "$what" "$n"; prev=$what
    fi
    if [ ! -f "$root/$file" ]; then echo "duplicate-surfaces: stale row, $file is gone ($what | $surface)" >&2; stale=1; mark="STALE"
    elif ! grep -qF -- "$label" "$root/$file"; then echo "duplicate-surfaces: stale row, $file no longer holds '$label' ($what | $surface)" >&2; stale=1; mark="STALE"
    else mark=""; fi
    printf -- '- [ ] %s — `%s` (`%s`)%s\n' "$surface" "$file" "$label" "${mark:+ **STALE**}"
  done <<ROWS
$rows
ROWS
} > "$out"
[ $stale = 0 ] && { echo "duplicate-surfaces: wrote $out ($(printf '%s\n' "$rows" | wc -l | tr -d ' ') rows)"; exit 0; }
echo "duplicate-surfaces: a row is stale: fix or delete it in $table" >&2
exit 1
